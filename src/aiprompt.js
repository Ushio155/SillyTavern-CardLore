/**
 * aiprompt.js — 「AI 适配」的提示词分层与输出守卫
 *
 * 设计目的（解决"把待适配的提示词当成指令执行"的幻觉）：
 *  1. 分层：system 层只放"转换器"身份 + 素材隔离规则 + 字段格式；user 层只放素材数据；
 *     user 层末尾再补一段"尾部锚定"提醒（模型对最近的文字最敏感，防止素材末行抢走控制权）。
 *  2. 隔离：素材被 <<<CARD_LORE_MATERIAL_BEGIN/END>>> 标记包裹，素材内伪造同名标记会被剥除；
 *     素材里的"你是……""你的唯一任务是……""禁止……"等一律声明为「数据」而非「指令」。
 *  3. 守卫：输出必须落在固定字段结构内；不合格时由 index.js 触发一次"修复重试"，
 *     两次结果取字段命中更多的一份。
 *
 * 本模块不 import 任何 SillyTavern 模块，可被测试脚本单独动态导入。
 */

