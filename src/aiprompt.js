export const CONTINUE_INSTRUCTION = '上面的转换结果在末尾被截断了。请从断点接着继续输出剩余内容：不要重复已经输出过的任何一行，不要重新开始，不要输出任何说明或开场白，只接续未完成的部分。';

/** 输出格式的必需要素（用于守卫打分） */
const STRONG_MARKERS = [
    /【角色卡】/,
    /【世界书】/,
    /名称\s*[:：]/,
    /描述\s*[:：]/,
    /系统提示\s*[:：]/,
    /开场白\s*[:：]/,
    /替代开场白\s*[:：]/,
    /示例对话\s*[:：]/,
    /关键词\s*[:：]/,
    /深度提示\s*[:：]/,
];

/** 只有命名字段行才算"结构正确"的核心证据 */
const CORE_MARKERS = [
    /名称\s*[:：]/,
    /描述\s*[:：]/,
    /系统提示\s*[:：]/,
    /开场白\s*[:：]/,
    /【角色卡】/,
    /【世界书】/,
];

/** 素材自带板块泄漏的信号（出现这些且缺少字段行 = 明显是"照素材模板作答"） */
const PERSONA_BLOCKS = [
    /【角色设定】/,
    /【开场节点】/,
    /【高级定义】/,
    /【绝对输出规则】/,
    /【区块映射规则】/,
];

/** 字段命中数（守卫打分，越高越像合法转换结果） */
export function conversionScore(text) {
    const s = String(text || '');
    return STRONG_MARKERS.filter(re => re.test(s)).length;
}

/**
 * 判断输出是否是可用的转换结果。
 * 规则：字段命中 ≥ 3 且至少命中一个核心字段行；同时排除"照素材模板作答"的形态。
 */
export function isConversionOutput(text) {
    const s = String(text || '');
    if (!s.trim()) return false;
    if (conversionScore(s) < 3) return false;
    if (!CORE_MARKERS.some(re => re.test(s))) return false;
    // 素材板块大量出现且几乎没有字段行 → 判定失败（避免"【角色设定】+【世界书】"式伪通过）
    const personaHits = PERSONA_BLOCKS.filter(re => re.test(s)).length;
    if (personaHits >= 2 && !/名称\s*[:：]/.test(s)) return false;
    return true;
}

/** 归一化：去掉空白与装饰符后做包含判断（只比较"字面是否保留"，不做语义） */
const normLine = (s) => String(s).replace(/[\s`·\-—*#>|]/g, '');

/** 忠实度门槛：素材有效行在输出里出现的比例低于此值即视为"没在转换，而是在另写" */
export const MIN_RETENTION = 0.25;

/**
 * 素材信息保留率：素材每个非空行（≥6 字）是否出现在输出里。
 * 结构化文档（短行多）才统计——散文/小说段落整段改写是正常的，不做判断（返回 1）。
 */
export function retentionRatio(material, output) {
    const lines = String(material || '').split('\n').map(s => s.trim()).filter(s => normLine(s).length >= 6);
    if (lines.length < 8) return 1;
    const avgLen = lines.reduce((n, l) => n + l.length, 0) / lines.length;
    if (avgLen > 80) return 1;                 // 长段落素材：允许概括改写
    const out = normLine(String(output || ''));
    if (!out) return 0;
    const hit = lines.filter(l => out.includes(normLine(l))).length;
    return hit / lines.length;
}

/** 忠实度守卫：结构对了但内容几乎全是新编的（幻觉）→ 也算不合格，触发重试 */
export function isFaithfulConversion(material, text) {
    return retentionRatio(material, text) >= MIN_RETENTION;
}

/* ------------------------------------------------------------------ *
 * 名称归属守卫：素材标题是"作品名/主题名"时，模型可能把用户角色当卡名
 * ------------------------------------------------------------------ */

/** 明显不是"卡名"的词（用于剔除文档小标题） */
const NON_NAME_WORDS = /(设定|规则|说明|模板|提示词|世界书|开场|示例|注意|备注|目录|简介|前言|结构|格式)/;
/** 章节名特征：只用于"光秃秃的 markdown 标题"这条最弱的兜底规则，避免把 ## 【世界书】/### 双数值系统 当成卡名 */
const SECTION_WORDS = /(设定|规则|说明|模板|提示词|世界书|开场|示例|注意|备注|目录|简介|前言|结构|格式|条目|关键词|数值|系统|机制|流程|类型|事件|阈值|常量|地点|随机|触发|内容|顺序|位置)/;
/** 名称归一化：去掉书名号/括号/空白/间隔符后比较 */
const normName = (s) => String(s || '').replace(/[\s《》〈〉【】\[\]（）()·・"'“”‘’,，.。:：;；\-—_/\\|]/g, '');

/** 章节/文档性文字（小说正文、大纲等素材的标题不是卡名） */
const CHAPTER_LIKE = /^(序|序章|楔子|引子|尾声|后记|前言|正文|全文|大纲|素材|样例|样张|目录|第[一二三四五六七八九十百零0-9]{1,3}[章节回幕部篇卷]?(\s|$|[:：、.。·-]).*)/;

/**
 * 从素材里提取"卡名/作品名"。
 * strong=true 表示素材里有显式的卡名声明（"角色卡名称"/"卡名:"/"标题:"/首行标题），
 * 这种可以放心用来校正输出；strong=false 只是"正文里出现过《书名》"的弱信号，仅作提示。
 * @returns {{name: string, strong: boolean, from: string}}
 */
export function extractMaterialTitle(material) {
    const text = String(material || '');
    const usable = (v) => Boolean(v) && v.length >= 2 && v.length <= 40
        && !NON_NAME_WORDS.test(v) && !CHAPTER_LIKE.test(v);

    /** 把"标签后面的那段话"清洗成名字：《书名》优先，否则取到句子断点为止 */
    const cleanAfterLabel = (raw) => {
        const s = String(raw || '');
        // 标签后面紧跟的是另一个【板块名】→ 说明这里没有写名字（例如"生成【角色卡名称】【角色设定】…五部分"）
        if (/^\s*[:：]?\s*[】\]]?\s*【/.test(s)) return '';
        const book = s.match(/《([^》\n]{1,40})》/);
        if (book) return book[1].trim();
        const cut = s.replace(/^[\s:：】\]"'“”]+/, '').split(/[\n。！？；;，,、]/)[0];
        return cut.replace(/[【】\[\]《》"'“”]/g, '').trim();
    };

    // ① 显式标签（可出现在任意位置）：角色卡名称 / 卡名 / 标题 / 作品名
    const labelRe = /(角色卡名称|卡名|标题|作品名)\s*[:：]?[ \t]*([^\n]*)/;
    const label = text.match(labelRe);
    if (label) {
        const v = cleanAfterLabel(label[2]);
        if (usable(v)) return { name: v, strong: true, from: '标签' };
    }
    const head = text.split('\n').map(s => s.trim()).filter(Boolean).slice(0, 8);
    // ② 开头几行里的标题行：《书名》标题 / 单独一行的《书名》
    for (const line of head) {
        const m = line.match(/^#{1,6}\s*[^\n《]*《([^》\n]{2,40})》/) || line.match(/^《([^》\n]{2,40})》$/);
        if (m && usable(m[1].trim())) return { name: m[1].trim(), strong: true, from: '标题行' };
    }
    // ③ 开头几行的 markdown **一级**标题（# 后面的文字即卡名；## / ### 是章节，不是卡名）
    for (const line of head) {
        const m = line.match(/^#\s+(.+)$/);
        if (!m) continue;
        const v = m[1].replace(/^【[^】]*】\s*/, '').replace(/[《》]/g, '').trim();
        if (!usable(v) || /[:：]/.test(v) || SECTION_WORDS.test(v)) continue;
        return { name: v, strong: true, from: '标题行' };
    }
    // ④ 弱信号：正文里第一次出现的《书名》
    const any = text.match(/《([^》\n]{2,40})》/);
    if (any && usable(any[1].trim())) return { name: any[1].trim(), strong: false, from: '正文《》' };
    return { name: '', strong: false, from: '' };
}

/** 取输出里的「名称」字段值 */
export function nameField(text) {
    const m = String(text || '').match(/^名称\s*[:：]\s*(.*)$/m);
    return m ? m[1].trim() : '';
}

/**
 * 名称校正：素材有显式卡名声明时，把输出「名称」行改写成该卡名。
 * - 输出名称与卡名一致（忽略书名号/括号/空白）→ 不动
 * - 输出名称夹带了卡名和别的名字（如"甲（《某某录》）"）→ 只留卡名
 * - 弱信号（仅正文里出现过《书名》）→ 不校正，只回报 expected 供调用方提示
 * @returns {{text: string, changed: boolean, expected: string, before: string, strong: boolean}}
 */
export function fixOutputName(text, material) {
    const src = String(text || '');
    const { name, strong } = extractMaterialTitle(material);
    const before = nameField(src);
    if (!name || !before) return { text: src, changed: false, expected: name, before, strong };
    if (normName(before) === normName(name)) return { text: src, changed: false, expected: name, before, strong };
    if (!strong) return { text: src, changed: false, expected: name, before, strong, weakOnly: true };
    return {
        text: src.replace(/^名称\s*[:：].*$/m, `名称: ${name}`),
        changed: true,
        expected: name,
        before,
        strong,
    };
}

/** 两次输出取更合格的一份：先比字段命中，再比素材保留率；同分取后者（后者带修复提示） */
export function pickBetterOutput(first, second, material) {
    const a = String(first || '');
    const b = String(second || '');
    if (!b.trim()) return a;
    if (!a.trim()) return b;
    const key = (t) => [conversionScore(t), material ? Math.round(retentionRatio(material, t) * 100) : 0];
    const ka = key(a);
    const kb = key(b);
    for (let i = 0; i < ka.length; i++) {
        if (kb[i] !== ka[i]) return kb[i] > ka[i] ? b : a;
    }
    return b;
}

/**
 * 末尾是否像被 max_tokens 截断：最后一行较长且没有句末标点。
 * （推理模型会把思维链算进 max_tokens，容易把正文挤断，故单独守卫一次）
 */
export function looksTruncated(text) {
    const lines = String(text || '').trimEnd().split('\n').map(s => s.trim()).filter(Boolean);
    if (!lines.length) return false;
    const last = lines[lines.length - 1];
    if (last.length < 24) return false;
    return !/[。！？…」』）)】”"'’》>:：;；,，、·\-—\]}]$/.test(last);
}

/**
 * 判断续写结果是否真的是"接着写"（而不是从头重来或寒暄），并合并。
 * @returns {string} 合并后的文本；若判定为重复/寒暄则返回原文本
 */
export function mergeContinuation(partial, continuation) {
    const a = String(partial || '');
    let b = String(continuation || '').trim();
    if (!b) return a;
    const probe = b.slice(0, 40).replace(/\s+/g, '');
    if (probe && a.replace(/\s+/g, '').includes(probe)) return a;   // 从头重来 → 丢弃
    // 寒暄式开头（"好的，我继续："）单独占一行时，只去掉那一行，保留后面的正文
    const head = b.split('\n')[0];
    if (/^(好的|明白了|收到|下面|以下是|我(会)?继续|继续)/.test(head) && b.includes('\n')) {
        b = b.split('\n').slice(1).join('\n').trim();
    }
    if (b.replace(/\s+/g, '').length < 12) return a;                // 太短，多半只是寒暄 → 丢弃
    return `${a.trimEnd()}\n${b}`;
}

/**
 * 构造分层消息：system = 转换规则；user = 素材预扫描提示 + 素材（带区块标记）+ 尾部锚定。
 * @param {string} promptText 提示词（用户可自行修改，默认 DEFAULT_AI_PROMPT）
 * @param {string} rawText 待转换素材
 * @returns {{role: string, content: string}[]}
 */
export function buildAiMessages(promptText, rawText) {
    const sys = String(promptText || DEFAULT_AI_PROMPT);
    // 素材中若伪造同名区块标记，剥除，避免模型误判边界
    const body = String(rawText ?? '').split(MATERIAL_OPEN).join('').split(MATERIAL_CLOSE).join('');
    // 机器预扫描：把"素材里的卡名/作品名"直接告知模型，降低它去抓用户角色名的概率
    const title = extractMaterialTitle(body);
    const scan = title.name
        ? `【素材预扫描·机器识别，仅供参考】这份素材里的卡名/作品名是「${title.name}」（来自${title.from}）。${title.strong
            ? '它是显式的卡名声明，请把它原样作为「名称」（只写名字本身，不要附加括号或其他名字）。'
            : '若素材的主角其实是被"你"指代的用户角色，请按【名称与角色归属】第 3 条处理，名称用这个作品名，用户角色写作 {{user}}。'}`
        : '';
    const user = [
        `【待转换素材开始】${MATERIAL_OPEN}`,
        body,
        `【待转换素材结束】${MATERIAL_CLOSE}`,
        '',
        scan,
        MATERIAL_TRAILER,
    ].filter(s => s !== '').join('\n');
    return [
        { role: 'system', content: sys },
        { role: 'user', content: user },
    ];
}
