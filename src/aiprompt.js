/**
 * aiprompt.js — 「AI 适配」的提示词分层与输出守卫
 *
 * 设计目的（解决三类幻觉）：
 *  1. 把待适配的素材当成指令执行：system 层只放"转换器"身份 + 素材隔离规则 + 字段格式，
 *     user 层只放素材数据 + 尾部锚定（模型对最近的文字最敏感，防止素材末行抢走控制权）。
 *  2. 抢错角色归属：素材标题是"作品名/主题名"、正文主角其实是被「你」指代的用户角色时，
 *     模型容易把用户角色当成卡牌名称与描述主体。用【名称与角色归属】规则 + 素材预扫描 +
 *     输出后名称校正三层拦住。
 *  3. 结构跑偏/内容另写/被截断：结构守卫、忠实度守卫、截断续写，由 index.js 触发重试。
 *
 * 本模块不 import 任何 SillyTavern 模块，可被测试脚本单独动态导入。
 */

